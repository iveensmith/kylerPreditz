import openNextHandler from "./.open-next/worker.js";

/**
 * @opennextjs/cloudflare's generated `.open-next/worker.js` only exports a
 * `fetch` handler (no built-in support for Cloudflare Cron Triggers as of
 * this adapter version - https://github.com/opennextjs/opennextjs-cloudflare
 * has no documented `scheduled` extension point). This thin wrapper is
 * wrangler.jsonc's real entry (see "main") instead of worker.js directly: it
 * passes `fetch` straight through unchanged, and adds `scheduled`, which maps
 * each cron expression to its existing `/api/cron/*` route and invokes
 * OpenNext's own `fetch` handler in-process with a synthetic Request - no
 * network round-trip, and the real route handler (auth check included) stays
 * the single source of truth, exactly as it already is for manual/dispatch
 * triggering.
 *
 * Plain JS on purpose: as a .ts file this got swept into `next build`'s own
 * TypeScript check (which runs before .open-next/worker.js exists, since
 * that's generated by the later opennextjs-cloudflare build step) despite
 * being excluded in tsconfig.json - Next's checker doesn't honor that
 * exclude. Wrangler bundles this with esbuild regardless of file extension.
 */

const CRON_ROUTE_BY_SCHEDULE = {
  "*/3 * * * *": "/api/cron/sync-results",
  "*/30 * * * *": "/api/cron/sync-stats",
  "0 */6 * * *": "/api/cron/sync-fixtures",
  "0 */2 * * *": "/api/cron/sync-team-stats",
  "0 * * * *": "/api/cron/generate-predictions",
};

export default {
  fetch: openNextHandler.fetch,

  async scheduled(event, env, ctx) {
    const path = CRON_ROUTE_BY_SCHEDULE[event.cron];
    if (!path) {
      console.error(`[scheduled] no route mapped for cron "${event.cron}"`);
      return;
    }
    if (!env.CRON_SECRET) {
      console.error("[scheduled] CRON_SECRET is not set");
      return;
    }

    const request = new Request(`https://internal.invalid${path}`, {
      headers: { Authorization: `Bearer ${env.CRON_SECRET}` },
    });
    const response = await openNextHandler.fetch(request, env, ctx);
    if (!response.ok) {
      console.error(`[scheduled] ${path} returned ${response.status}: ${await response.text()}`);
    }
  },
};
